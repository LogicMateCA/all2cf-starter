export function renderDesignCSS(profile) {
  const { light, dark } = profile.semanticColors;
  const { radius, motion, fontUi, fontDisplay, fontMono } = profile.tokens;
  const mode = (colors) => [
    `  --design-background: ${colors.background};`,
    `  --design-surface: ${colors.surface};`,
    `  --design-surface-strong: color-mix(in srgb, ${colors.surface} 82%, ${colors.background});`,
    `  --design-foreground: ${colors.foreground};`,
    `  --design-muted: ${colors.muted};`,
    `  --design-accent: ${colors.accent};`,
    `  --design-on-accent: ${colors.onAccent};`,
    `  --design-border: ${colors.border};`,
    `  --design-danger: ${colors.danger};`,
    "  --canvas: var(--design-background);",
    "  --surface: var(--design-surface);",
    "  --surface-soft: var(--design-surface-strong);",
    "  --text: var(--design-foreground);",
    "  --muted: var(--design-muted);",
    "  --subtle: color-mix(in srgb, var(--design-muted) 76%, var(--design-background));",
    "  --border: var(--design-border);",
    "  --strong: color-mix(in srgb, var(--design-border) 58%, var(--design-foreground));",
    "  --accent: var(--design-accent);",
    "  --accent-soft: color-mix(in srgb, var(--design-accent) 12%, var(--design-background));",
    "  --danger: var(--design-danger);",
    "  --sl-color-accent-low: color-mix(in srgb, var(--design-accent) 14%, var(--design-background));",
    "  --sl-color-accent: var(--design-accent);",
    "  --sl-color-accent-high: color-mix(in srgb, var(--design-accent) 36%, var(--design-foreground));",
    "  --sl-color-white: var(--design-foreground);",
    "  --sl-color-gray-1: color-mix(in srgb, var(--design-foreground) 92%, var(--design-background));",
    "  --sl-color-gray-2: color-mix(in srgb, var(--design-foreground) 78%, var(--design-background));",
    "  --sl-color-gray-3: var(--design-muted);",
    "  --sl-color-gray-4: color-mix(in srgb, var(--design-border) 78%, var(--design-foreground));",
    "  --sl-color-gray-5: var(--design-border);",
    "  --sl-color-gray-6: var(--design-surface-strong);",
    "  --sl-color-black: var(--design-background);",
  ].join("\n");
  return [
    "/* Generated by scripts/materialize-blueprint.mjs. Do not edit by hand. */",
    `/* ${profile.id}@${profile.version} */`,
    ":root {",
    `  --design-profile: ${JSON.stringify(profile.id)};`,
    `  --design-font-ui: ${fontUi};`,
    `  --design-font-display: ${fontDisplay};`,
    `  --design-font-mono: ${fontMono};`,
    `  --design-radius-sm: ${radius.sm}px;`,
    `  --design-radius-md: ${radius.md}px;`,
    `  --design-radius-lg: ${radius.lg}px;`,
    `  --design-motion-fast: ${motion.fastMs}ms;`,
    `  --design-motion-standard: ${motion.standardMs}ms;`,
    "  --sl-font: var(--design-font-ui);",
    "  --radius-sm: var(--design-radius-sm);",
    "  --radius-md: var(--design-radius-md);",
    "  --radius-lg: var(--design-radius-lg);",
    mode(light),
    "}",
    ":root[data-theme=\"dark\"] {",
    mode(dark),
    "}",
    "@media (prefers-color-scheme: dark) {",
    "  :root:not([data-theme=\"light\"]) {",
    mode(dark),
    "  }",
    "}",
    "",
  ].join("\n");
}

export function renderMobileDesign(profile) {
  return [
    "// Generated by scripts/materialize-blueprint.mjs. Do not edit by hand.",
    `export const generatedMobileDesign = ${JSON.stringify({ profileId: profile.id, version: profile.version, light: profile.semanticColors.light, dark: profile.semanticColors.dark, fonts: { ui: profile.tokens.fontMobileUi, display: profile.tokens.fontMobileDisplay }, radius: profile.tokens.radius, motion: profile.tokens.motion }, null, 2)} as const;`,
    "",
  ].join("\n");
}
